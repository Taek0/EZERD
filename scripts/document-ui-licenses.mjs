import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
const root = new URL('../', import.meta.url);
const listing = spawnSync(
  process.platform === 'win32' ? 'cmd.exe' : 'pnpm',
  process.platform === 'win32'
    ? ['/d', '/s', '/c', 'pnpm --filter @ezerd/web list --prod --depth Infinity --json']
    : ['--filter', '@ezerd/web', 'list', '--prod', '--depth', 'Infinity', '--json'],
  { cwd: fileURLToPath(root), encoding: 'utf8' },
);
if (listing.error) throw listing.error;
if (listing.status !== 0) throw new Error('Unable to list UI runtime dependencies');
const packages = new Map();
function walk(node) {
  for (const field of ['dependencies', 'optionalDependencies'])
    for (const [name, dep] of Object.entries(node[field] ?? {})) {
      if (!dep.version.startsWith('link:'))
        packages.set(name + '@' + dep.version, { name, ...dep });
      walk(dep);
    }
}
JSON.parse(listing.stdout).forEach(walk);
let result = '# Browser UI third-party notices\n\n';
result +=
  'Generated by pnpm docs:ui-licenses. This includes installed browser runtime dependencies; tree shaking may omit portions from a particular build. Local application code and user-supplied font assets are not licensed by this notice.\n\n';
result +=
  '## Untitled UI React adapted free components\n\nSource: https://github.com/untitleduico/react/tree/c981a73bcd6b6c68d2a54070f20f020191212828\n\nThe shared UI adapts free base component recipes and React Aria behavior to EZERD native events, existing layouts and blue tokens. Context-menu positioning and composition helpers are local additions. No PRO or external icon assets are included.\n\n';
result += await readFile(new URL('apps/web/third-party/untitled-ui.LICENSE', root), 'utf8');
const groups = new Map();
for (const item of [...packages.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  const manifest = JSON.parse(await readFile(join(item.path, 'package.json'), 'utf8'));
  const files = (await readdir(item.path, { withFileTypes: true })).filter(
    (entry) => entry.isFile() && /^(licen[sc]e|notice|copying)(?:$|[._-])/i.test(entry.name),
  );
  if (
    !files.length &&
    item.name === 'client-only' &&
    manifest.version === '0.0.1' &&
    !(await readFile(join(item.path, 'index.js'), 'utf8')).trim()
  ) {
    result +=
      '\n\n## client-only@0.0.1\n\nThe package metadata declares MIT. Its browser entry index.js is empty; no marker implementation is emitted into this browser bundle. The published package includes no LICENSE file.\n';
    continue;
  }
  if (!files.length) throw new Error('Missing distributed license text: ' + item.name);
  const text = (
    await Promise.all(
      files.map(
        async (file) => file.name + '\n\n' + (await readFile(join(item.path, file.name), 'utf8')),
      ),
    )
  ).join('\n\n');
  const names = groups.get(text) ?? [];
  names.push(`${item.name}@${manifest.version} (${manifest.license ?? 'see text'})`);
  groups.set(text, names);
}
for (const [text, names] of groups) result += '\n\n## ' + names.join(', ') + '\n\n' + text.trim();
result += '\n';
await writeFile(new URL('apps/web/THIRD_PARTY_NOTICES.md', root), result);
await writeFile(new URL('apps/web/public/THIRD_PARTY_NOTICES.txt', root), result);
console.log(
  `Documented ${packages.size} browser runtime packages plus Untitled UI adapted source.`,
);
